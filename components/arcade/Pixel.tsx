type Props = { name: string; size: string; className?: string; title?: string };

export function Pixel({ name, size, className = '', title }: Props) {
  const rows = SPRITES[name] ?? SPRITES.chip;
  const w = Math.max(...rows.map((r) => r.length));
  const h = rows.length;
  const rects: React.ReactNode[] = [];
  const fill: Record<string, string> = { '#': 'var(--ink)', o: 'var(--mid)', '+': 'var(--lite)' };
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const c = row[x];
      if (!fill[c]) { x++; continue; }
      let e = x;
      while (e + 1 < row.length && row[e + 1] === c) e++;
      rects.push(<rect key={`${x}-${y}`} x={x} y={y} width={e - x + 1} height={1} fill={fill[c]} />);
      x = e + 1;
    }
  });
  return (
    <svg
      className={`px ${className}`}
      viewBox={`0 0 ${w} ${h}`}
      style={{ width: size, aspectRatio: `${w} / ${h}` }}
      shapeRendering="crispEdges"
      role={title ? 'img' : undefined}
      aria-label={title}
      aria-hidden={title ? undefined : true}
    >
      {rects}
    </svg>
  );
}
